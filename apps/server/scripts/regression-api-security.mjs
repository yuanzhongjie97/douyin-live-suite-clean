import assert from 'node:assert/strict';
import Fastify from 'fastify';
import cors from '@fastify/cors';

const security = await import('../src/security.ts');

assert.equal(
  security.isAllowedLocalApiOrigin(undefined),
  true,
  'same-origin requests without Origin header should be allowed',
);
assert.equal(
  security.isAllowedLocalApiOrigin('http://127.0.0.1:3100'),
  true,
  'desktop renderer origin should be allowed',
);
assert.equal(
  security.isAllowedLocalApiOrigin('http://localhost:5173'),
  true,
  'Vite dev origin should be allowed',
);
assert.equal(
  security.isAllowedLocalApiOrigin('https://evil.example'),
  false,
  'remote browser origins must not be allowed to read local API responses',
);
assert.equal(
  security.isAllowedLocalApiOrigin('null'),
  false,
  'sandboxed/file origins must not be treated as local API origins',
);
assert.equal(
  security.isAllowedLocalApiOrigin('file:///C:/tmp/index.html'),
  false,
  'file origins must not be treated as local API origins',
);

assert.equal(
  security.isCrossSiteStateChangingRequest({
    method: 'POST',
    origin: 'https://evil.example',
    secFetchSite: 'cross-site',
  }),
  true,
  'cross-site state changing requests must be rejected before reaching service code',
);
assert.equal(
  security.isCrossSiteStateChangingRequest({
    method: 'POST',
    origin: 'http://127.0.0.1:3100',
    secFetchSite: 'same-origin',
  }),
  false,
  'same-origin state changing requests should preserve desktop behavior',
);
assert.equal(
  security.isCrossSiteStateChangingRequest({
    method: 'GET',
    origin: 'https://evil.example',
    secFetchSite: 'cross-site',
  }),
  false,
  'GET requests are handled by CORS and should not be blocked by state-change guard',
);
assert.equal(
  security.isCrossSiteStateChangingRequest({
    method: 'POST',
    origin: 'null',
    secFetchSite: 'none',
  }),
  true,
  'Origin null state changing requests must be rejected before reaching service code',
);

assert.equal(
  security.normalizeAllowedDouyinLiveUrl('https://live.douyin.com/1234567890?foo=bar#x'),
  'https://live.douyin.com/1234567890',
  'live room URLs should normalize to stable https live.douyin.com room URLs',
);
assert.equal(
  security.normalizeAllowedDouyinEntryUrl('https://www.douyin.com/'),
  'https://www.douyin.com',
  'login entry should allow the Douyin home page',
);
assert.equal(
  security.normalizeAllowedDouyinEntryUrl('https://www.douyin.com/user/MS4wLjABAAAA1234567890'),
  'https://www.douyin.com/user/MS4wLjABAAAA1234567890',
  'profile URLs should stay allowed for user profile entry points',
);
assert.equal(
  security.normalizeAllowedDouyinEntryUrl('https://www.douyin.com/search/%E7%94%A8%E6%88%B7?type=user'),
  'https://www.douyin.com/search/%E7%94%A8%E6%88%B7?type=user',
  'search URLs generated by the app should stay allowed',
);
assert.equal(
  security.normalizeAllowedDouyinLiveUrl('https://www.douyin.com/user/MS4wLjABAAAA1234567890'),
  undefined,
  'start session should reject non-live Douyin pages',
);
assert.equal(
  security.normalizeAllowedDouyinEntryUrl('http://live.douyin.com/1234567890'),
  undefined,
  'plain http Douyin URLs should be rejected',
);
assert.equal(
  security.normalizeAllowedDouyinEntryUrl('https://evil.example/live.douyin.com/1234567890'),
  undefined,
  'non-Douyin hostnames should be rejected',
);
assert.equal(
  security.normalizeAllowedDouyinEntryUrl('https://live.douyin.com.evil.example/1234567890'),
  undefined,
  'host confusion suffixes should be rejected',
);

const app = Fastify({ logger: false });
const runtimeToken = 'test-local-api-token';
await app.register(cors, {
  origin: (origin, callback) => {
    callback(null, security.isAllowedLocalApiOrigin(origin));
  },
});
app.addHook('preHandler', async (request, reply) => {
  if (request.url.startsWith('/api/') && request.headers.origin && !security.isAllowedLocalApiOrigin(request.headers.origin)) {
    return reply.status(403).send({ message: 'blocked origin' });
  }
  if (
    security.isCrossSiteStateChangingRequest({
      method: request.method,
      origin: request.headers.origin,
      secFetchSite: request.headers['sec-fetch-site'],
    })
  ) {
    return reply.status(403).send({ message: 'blocked' });
  }
  if (request.url.startsWith('/api/') && !security.hasValidLocalApiToken(request.headers, runtimeToken)) {
    return reply.status(401).send({ message: 'unauthorized' });
  }
});

let stateChangingHandlerCalled = false;
app.post('/api/state-change', async () => {
  stateChangingHandlerCalled = true;
  return { ok: true };
});
app.get('/api/read', async () => ({ ok: true }));
app.get('/api/sessions/active', async () => ({ ok: true }));
app.get('/api/events', async () => ({ ok: true }));
app.get('/api/export.xlsx', async () => 'xlsx');
app.get('/api/events/stream', async () => 'stream');
await app.ready();

const blockedPost = await app.inject({
  method: 'POST',
  url: '/api/state-change',
  headers: {
    origin: 'https://evil.example',
    'sec-fetch-site': 'cross-site',
    cookie: security.serializeLocalApiCookie(runtimeToken),
  },
});
assert.equal(blockedPost.statusCode, 403, 'cross-site POST should be rejected');
assert.equal(stateChangingHandlerCalled, false, 'rejected POST must not reach state changing handler');

const allowedPost = await app.inject({
  method: 'POST',
  url: '/api/state-change',
  headers: {
    origin: 'http://127.0.0.1:3100',
    'sec-fetch-site': 'same-origin',
    cookie: security.serializeLocalApiCookie(runtimeToken),
  },
});
assert.equal(allowedPost.statusCode, 200, 'same-origin POST should still reach local API');

const blockedNullOriginPost = await app.inject({
  method: 'POST',
  url: '/api/state-change',
  headers: {
    origin: 'null',
    'sec-fetch-site': 'none',
    cookie: security.serializeLocalApiCookie(runtimeToken),
  },
});
assert.equal(blockedNullOriginPost.statusCode, 403, 'Origin null POST should be rejected');

const blockedRead = await app.inject({
  method: 'GET',
  url: '/api/read',
  headers: {
    origin: 'https://evil.example',
    cookie: security.serializeLocalApiCookie(runtimeToken),
  },
});
assert.equal(blockedRead.statusCode, 403, 'invalid Origin GET should be rejected before reading local data');
assert.equal(
  blockedRead.headers['access-control-allow-origin'],
  undefined,
  'remote origins should not receive CORS read permission',
);

const blockedNullOriginRead = await app.inject({
  method: 'GET',
  url: '/api/read',
  headers: {
    origin: 'null',
    cookie: security.serializeLocalApiCookie(runtimeToken),
  },
});
assert.equal(blockedNullOriginRead.statusCode, 403, 'Origin null GET should be rejected before reading local data');

for (const url of ['/api/sessions/active', '/api/events', '/api/export.xlsx', '/api/events/stream']) {
  const unauthorized = await app.inject({
    method: 'GET',
    url,
    headers: {
      origin: 'http://127.0.0.1:3100',
    },
  });
  assert.equal(unauthorized.statusCode, 401, `${url} should reject requests without local API cookie`);

  const authorized = await app.inject({
    method: 'GET',
    url,
    headers: {
      origin: 'http://127.0.0.1:3100',
      cookie: security.serializeLocalApiCookie(runtimeToken),
    },
  });
  assert.equal(authorized.statusCode, 200, `${url} should accept requests with local API cookie`);
}

await app.close();

console.log('api security regression checks passed');
